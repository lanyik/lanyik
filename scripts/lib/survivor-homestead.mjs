import { mkdir, writeFile, cp } from "node:fs/promises";
import { resolve } from "node:path";
import { Float32BufferAttribute, Vector3 } from "three";
import { OBJLoader } from "three/examples/jsm/loaders/OBJLoader.js";
import { mergeGeometries, mergeVertices } from "three/examples/jsm/utils/BufferGeometryUtils.js";
import { sourceReader } from "./actor-source.mjs";

/** Preserve Quaternius geometry and linear MTL colours; one draw per building, no runtime OBJ parsing. */
export async function prepareSurvivorHomestead(input, output, dimensionsFile) {
    const read = await sourceReader(input), models = {}, dimensions = {};
    for (const [name, span] of [["Inn", 8], ["Blacksmith", 7], ["House_1", 6], ["Well", 2]]) {
        const colours = new Map(); let current;
        for (const line of (await read(`${name}.mtl`)).toString("utf8").split(/\r?\n/)) {
            const [key, ...values] = line.trim().split(/\s+/);
            if (key === "newmtl") current = values.join(" ");
            if (key === "Kd") colours.set(current, values.map(Number));
            if (key.startsWith("map_")) throw new Error(`${name}: textured materials require explicit baking`);
        }
        // Blender exports loose construction edges in Inn/Well; OBJLoader otherwise treats the entire object as lines.
        const triangles = (await read(`${name}.obj`)).toString("utf8").replace(/^l\s+.*$/gm, "");
        const scene = new OBJLoader().parse(triangles), parts = [];
        scene.updateMatrixWorld(true);
        scene.traverse(mesh => {
            if (!mesh.isMesh) return;
            const geometry = mesh.geometry.clone().applyMatrix4(mesh.matrixWorld);
            const coloursAttribute = new Float32Array(geometry.getAttribute("position").count * 3);
            const materials = Array.isArray(mesh.material) ? mesh.material : [mesh.material];
            const groups = geometry.groups.length ? geometry.groups : [{ start: 0, count: coloursAttribute.length / 3, materialIndex: 0 }];
            for (const group of groups) {
                const colour = colours.get(materials[group.materialIndex].name);
                if (!colour) throw new Error(`${name}: missing source material`);
                for (let vertex = group.start; vertex < group.start + group.count; vertex++) coloursAttribute.set(colour, vertex * 3);
            }
            geometry.setAttribute("color", new Float32BufferAttribute(coloursAttribute, 3));
            geometry.deleteAttribute("uv"); geometry.clearGroups(); parts.push(geometry);
            mesh.geometry.dispose(); materials.forEach(material => material.dispose());
        });
        const merged = mergeGeometries(parts), geometry = mergeVertices(merged);
        parts.forEach(part => part.dispose()); merged.dispose(); geometry.computeBoundingBox();
        const center = geometry.boundingBox.getCenter(new Vector3()), size = geometry.boundingBox.getSize(new Vector3());
        const scale = span / Math.max(size.x, size.z);
        geometry.translate(-center.x, -geometry.boundingBox.min.y, -center.z); geometry.scale(scale, scale, scale);
        dimensions[name] = { width: size.x * scale, depth: size.z * scale, height: size.y * scale };
        const json = geometry.toJSON(); delete json.uuid; models[name] = json; geometry.dispose();
    }
    await read("License.txt"); await mkdir(output, { recursive: true });
    await writeFile(resolve(output, "models.json"), JSON.stringify(models));
    await writeFile(dimensionsFile, `// Generated by scripts/lib/survivor-homestead.mjs from the licensed source meshes.\nexport const HOMESTEAD_MODELS = ${JSON.stringify(dimensions, null, 4)} as const;\n`);
    for (const file of ["License.txt", "sources.json"]) await cp(resolve(input, file), resolve(output, file));
}
